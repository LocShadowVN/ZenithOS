pub fn draw_glyph_8x8(fb: &FramebufferInfo, glyph: [u8; 8], style: GlyphStyle) {
    for (row_idx, &row_bits) in glyph.iter().enumerate() {
        for col_idx in 0..8u32 {
            if (row_bits & (1 << (7 - col_idx))) != 0 {
                fb_fill_rect(
                    fb,
                    Rect {
                        x: style.x + col_idx * style.scale,
                        y: style.y + (row_idx as u32) * style.scale,
                        w: style.scale,
                        h: style.scale,
                    },
                    style.color,
                );
            }
        }
    }
}

/// Initializes a standard monochrome/VGA hardware framebuffer console (`fbcon`).
pub fn init_fbcon(fb: &FramebufferInfo) {
    // Clear screen to standard black (0x000000)
    fb_fill_rect(
        fb,
        Rect {
            x: 0,
            y: 0,
            w: fb.width,
            h: fb.height,
        },
        0x0000_0000,
    );

    // 1px horizontal divider for the console header
    fb_fill_rect(
        fb,
        Rect {
            x: 0,
            y: 20,
            w: fb.width,
            h: 1,
        },
        0x0040_4040,
    );

    let header = b"ZENITH-OS FBCON (x86_64 LINUX ABI)";
    for (i, &ch) in header.iter().enumerate() {
        draw_glyph_8x8(
            fb,
            ascii_to_glyph_8x8(ch),
            GlyphStyle {
                x: 8 + (i as u32) * 8,
                y: 6,
                scale: 1,
                color: 0x00E0_E0E0,
            },
        );
    }
}
